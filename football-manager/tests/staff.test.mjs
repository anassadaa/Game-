import test from 'node:test'; import assert from 'node:assert/strict';
import { newGame, startMatch, advanceWeek } from '../src/game.ts';
import { simToEnd } from '../src/highlights.ts';
import { canHire, hireStaff, sackStaff, staffLimit, staffCount, assistantAdvice, coachBoost } from '../src/staff.ts';
import { encodeSave, decodeSave } from '../src/save.ts';
test('staff market, hiring rules, sacking with compensation, effects', () => {
  let s = newGame(11, 'arsenal', 60);
  assert.ok(s.staffMarket.length >= 8);
  const star = { ...s.staffMarket[0], rep: 100, id: 'x1' };
  s.staffMarket.push(star);
  assert.match(canHire(s, star), /bigger job/);
  const ok = s.staffMarket.find((x) => !canHire(s, x));
  assert.ok(ok);
  s = hireStaff(s, ok.id);
  assert.equal(staffCount(s), 1);
  const asst = { ...ok, id: 'a1', role: 'assistant', rep: 0, wage: 1 };
  s.staffMarket.push(asst); s = hireStaff(s, 'a1');
  assert.ok(assistantAdvice(s).talk);
  const coach = { ...ok, id: 'c1', role: 'attack', rating: 20, rep: 0, wage: 1 };
  s.staffMarket.push(coach); s = hireStaff(s, 'c1');
  assert.ok(coachBoost(s, s.players.find((p) => p.position === 'FW')) > 1.5);
  assert.ok(staffLimit(s) >= 5);
  const b0 = s.budget; s = sackStaff(s, 'c1');
  assert.ok(s.budget < b0);
  for (let w = 0; w < 3; w++) s = advanceWeek(simToEnd(startMatch(s)));
  assert.ok(decodeSave(encodeSave(s)));
  const old = JSON.parse(encodeSave(s)); delete old.staff; delete old.staffMarket;
  assert.ok(decodeSave(JSON.stringify(old)).staffMarket.length);
});
