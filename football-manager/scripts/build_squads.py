"""Build look-alike first-team squads for Touchline with DuckDB.

Inputs (public data, fetched by fetch_squads.py + fetch_wikidata.py):
  data/wp_squads.json  club id -> [[name, pos, nation, wiki title], ...] from Wikipedia squad tables
  data/wd_info.json    wiki title -> [birth year, sitelink count] from Wikidata
Club ratings come from src/world.ts. Output: src/squads.ts (compact strings).
Real names are never written: every surname gets consistent parody letter swaps.
Usage: python3 scripts/build_squads.py
"""
import json, re, unicodedata, pathlib, duckdb

ROOT = pathlib.Path(__file__).resolve().parent.parent
D = ROOT / "scripts" / "data"
YEAR = 2026
MAX_PER_CLUB = 25

# Ordered suffix/infix swaps; first match wins, so the same name always maps the same way.
RULES = [
    ("son$", "sen"), ("sen$", "son"), ("ez$", "es"), ("es$", "ez"), ("ski$", "sky"), ("sky$", "ski"),
    ("ic$", "ich"), ("ich$", "ic"), ("ck", "k"), ("ph", "f"), ("th", "t"), ("ou", "oo"), ("ee", "ea"),
    ("ie$", "y"), ("y$", "ie"), ("i$", "y"), ("o$", "oh"), ("a$", "ah"), ("e$", "ay"), ("er$", "ar"),
    ("an$", "ann"), ("on$", "onn"), ("in$", "inn"), ("el$", "ell"), ("al$", "all"), ("ll", "l"), ("tt", "t"),
    ("ss", "s"), ("w", "v"), ("v", "w"), ("k", "c"), ("c", "k"), ("z", "s"), ("s$", "z"),
]

def ascii_(s: str) -> str:
    return unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()

REAL: set[str] = set()  # every real surname, so a twist never lands on another real player's name

def twist(word: str) -> str:
    low = word.lower()
    for pat, rep in RULES:
        new = re.sub(pat, rep, low, count=1)
        if new != low and new not in REAL:
            return new[:1].upper() + new[1:]
    return word + ("e" if not low.endswith("e") else "r")

def parody(name: str) -> str:
    name = re.sub(r"\s*\(.*?\)", "", ascii_(name)).strip()
    parts = name.split()
    if not parts:
        return "Joe Bloggs"
    parts[-1] = "-".join(twist(p) for p in parts[-1].split("-"))
    if len(parts) > 1 and len(parts[0]) > 4 and sum(map(ord, parts[0])) % 3 == 0:
        parts[0] = twist(parts[0])  # some first names change too, deterministically
    out = " ".join(parts)
    return out if out.lower() != name.lower() else out + "o"

def club_ratings():
    src = (ROOT / "src" / "world.ts").read_text()
    return {m[0]: int(m[1]) for m in re.findall(r"([a-z]+)\|[^|,`]+\|(\d+)", src)}

sq = json.loads((D / "wp_squads.json").read_text())
REAL.update(w.lower() for rows in sq.values() for r in rows for w in re.split(r"[\s-]+", ascii_(r[0])))
con = duckdb.connect()
con.create_function("parody", parody, [str], str)
sq = json.loads((D / "wp_squads.json").read_text())
info = json.loads((D / "wd_info.json").read_text())
con.execute("CREATE TABLE raw(club VARCHAR, ord INT, name VARCHAR, pos VARCHAR, nat VARCHAR, title VARCHAR)")
con.executemany("INSERT INTO raw VALUES (?,?,?,?,?,?)",
                [(c, i, *r) for c, rows in sq.items() for i, r in enumerate(rows)])
con.execute("CREATE TABLE wd(title VARCHAR, born INT, fame INT)")
con.executemany("INSERT INTO wd VALUES (?,?,?)",
                [(t, int(v[0]) if v and v[0] and v[0].isdigit() else None, v[1] if v else 0) for t, v in info.items()])
con.execute("CREATE TABLE clubs(club VARCHAR, rating INT)")
con.executemany("INSERT INTO clubs VALUES (?,?)", list(club_ratings().items()))

rows = con.execute(f"""
WITH p AS (
  SELECT DISTINCT ON (r.club, r.name) r.club, r.ord, r.name, r.pos, c.rating AS club_rating,
         COALESCE({YEAR} - wd.born, 25) AS age, COALESCE(wd.fame, 0) AS fame
  FROM raw r JOIN clubs c USING (club) LEFT JOIN wd USING (title)
  WHERE r.pos IN ('GK','DF','MF','FW')
), ranked AS (
  SELECT *, row_number() OVER (PARTITION BY club ORDER BY fame DESC, ord) AS fr,
         count(*) OVER (PARTITION BY club) AS n
  FROM p WHERE age BETWEEN 16 AND 42
), kept AS (
  SELECT *, percent_rank() OVER (PARTITION BY club ORDER BY fame DESC, ord) AS pr
  FROM ranked WHERE fr <= {MAX_PER_CLUB}
)
SELECT club, parody(name) AS name, pos, age,
       least(93, greatest(45, round(club_rating + 5 - 16 * pr
             - CASE WHEN age <= 19 THEN 4 WHEN age >= 35 THEN 2 ELSE 0 END)))::INT AS rating
FROM kept ORDER BY club, rating DESC, name
""").fetchall()

squads: dict[str, list[str]] = {}
for club, name, pos, age, rating in rows:
    squads.setdefault(club, []).append(f"{name.replace('|', '').replace(';', '')}|{pos}|{age}|{rating}")
lines = ",\n".join(f"  {c}: {json.dumps(';'.join(v))}" for c, v in sorted(squads.items()))
(ROOT / "src" / "squads.ts").write_text(
    "// GENERATED by scripts/build_squads.py (DuckDB). Parody look-alike names only; do not edit by hand.\n"
    "// club: 'Name|POS|age|rating;...'\n"
    f"export const SQUADS: Record<string, string> = {{\n{lines},\n}};\n")
con.close()
print(f"{len(rows)} players across {len(squads)} clubs -> src/squads.ts")
